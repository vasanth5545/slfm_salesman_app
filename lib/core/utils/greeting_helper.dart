  // 🔥 In-time Late aaga vanthaal varum System Message (Half day warnings)
  static String? getLateClockInMessage(DateTime inTime,
      {String? customCutoff}) {
    // Convert current clock-in time to total minutes for comparison
    int totalMinutes = (inTime.hour * 60) + inTime.minute;

    // 1. Specific Salesman Logic (Custom Cutoff provided)
    if (customCutoff != null && customCutoff.isNotEmpty) {
      try {
        final parts = customCutoff.split(':');
        if (parts.length >= 2) {
          int h = int.tryParse(parts[0]) ?? 10;
          int m = int.tryParse(parts[1]) ?? 0;
          int cutoffMinutes = (h * 60) + m;

          if (totalMinutes > cutoffMinutes) {
            String amPm = h >= 12 ? "PM" : "AM";
            int displayH = h > 12 ? h - 12 : (h == 0 ? 12 : h);
            String timeStr = "$displayH:${m.toString().padLeft(2, '0')} $amPm";
            // இது கஸ்டம் கட்-ஆஃப் (10:30 போன்றவை) உள்ளவர்களுக்கு மட்டும் வரும்
            return "உங்களுக்கு கொடுத்த நேரமே $timeStr, அதிலும் லேட்டா வந்திருக்கீங்க... உங்களுக்கு 'Half Day' தான், போங்க!! 😈";
          }
        }
      } catch (e) {
        // Fallback if parsing fails
      }
    } else {
      // 2. Normal Salesman Logic: After 10:00 AM (600 minutes)
      const int globalCutoff = 600; // 10:00 AM
      if (totalMinutes > globalCutoff) {
        return "நேரம் கடந்துவிட்டது! நீங்கள் தாமதமாக வந்துள்ளீர்கள் (Half Day). ⏰";
      }
    }

    // On-time ஆக வந்திருந்தால் எந்த மெசேஜும் வராது
    return null;
  }
